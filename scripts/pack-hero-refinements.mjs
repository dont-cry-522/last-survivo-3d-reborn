import fs from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {parseArgs} from 'node:util';

// Freeze v216's actual delivered selection, including retained v215 outfits.
// Usage: node scripts/pack-hero-refinements.mjs --replace=lingya:attire
// Repeat --replace for other approved v217 surfaces. --check writes nothing.
const {values}=parseArgs({options:{replace:{type:'string',multiple:true},check:{type:'boolean'}}});
const selected=values.replace||[];
if(!selected.length)throw Error('Name approved v217 parts explicitly: --replace=lingya:attire');
if(new Set(selected).size!==selected.length)throw Error('Duplicate replacement selection');
const root=new URL('../',import.meta.url),folder='assets/characters/rebuilt-v217/',dir=new URL(folder,root);
const baseline=JSON.parse(await fs.readFile(new URL('assets/characters/rebuilt-v216/sources.json',root),'utf8'));
const originals=new Map(baseline.files.map(entry=>[entry.kind+':'+entry.part,entry]));
if(originals.size!==14)throw Error('Incomplete immutable v216 asset baseline');
for(const key of selected)if(!originals.has(key))throw Error('Unknown hero surface '+key);
const replacementKeys=new Set(selected),files=[],pending=[];
const sha=data=>createHash('sha256').update(data).digest('hex');
const sourceScripts={lingya:'prepare-lingya-v217.py',silver:'prepare-silver-v217.py',tide:'prepare-tide-v217.py',
 wraith:'prepare-masked-sleeves-v217.py',wuling:'prepare-masked-sleeves-v217.py',mirage:'prepare-masked-sleeves-v217.py'};
for(const [key,entry]of originals){
 const original=await fs.readFile(new URL(entry.file,root));
 if(original.length!==entry.bytes||sha(original)!==entry.sha256)throw Error('Original delivered asset was changed: '+entry.file);
 if(!replacementKeys.has(key)){files.push({...entry});continue;}
 const name=entry.kind+'-'+entry.part,data=await fs.readFile(new URL(folder+name+'.glb',root)),sha256=sha(data);
 if(data.length<20||data.length>=2_000_000||data.readUInt32LE(0)!==0x46546c67||data.readUInt32LE(8)!==data.length)throw Error('Invalid or over-budget GLB: '+name);
 const file=folder+name+'-'+sha256.slice(0,12)+'.glb';
 pending.push({file,data});files.push({kind:entry.kind,part:entry.part,file,bytes:data.length,sha256});
}
const provenance=[215,216,217].flatMap(version=>['sources.json','LICENSE.txt'].map(name=>'assets/characters/rebuilt-v'+version+'/'+name));
const result={version:217,approved:selected,files:files.length,bytes:files.reduce((n,file)=>n+file.bytes,0),heroes:[...new Set(files.map(file=>file.kind))]};
if(values.check){console.log(JSON.stringify(result));process.exit(0);}
await fs.access(new URL('LICENSE.txt',dir));
for(const file of provenance.filter(file=>!file.endsWith('rebuilt-v217/sources.json')))await fs.access(new URL(file,root));
for(const {file,data}of pending)await fs.writeFile(new URL(file,root),data);
await fs.writeFile(new URL('sources.json',dir),JSON.stringify({
 version:217,author:'Quaternius and local project mesh adaptations',retrieved:'2026-10-18',
 sourceLicense:'CC0-1.0',licenseURL:'https://creativecommons.org/publicdomain/zero/1.0/',
 sources:[
  {url:'https://quaternius.com/packs/universalbasecharacters.html',purpose:'Existing free Standard Superhero male/female bases. Other advertised full-pack body types have not been adopted.'},
  {url:'https://quaternius.com/packs/modularcharacteroutfitsfantasy.html',purpose:'Existing free Standard male/female Ranger and Peasant outfits; original rigs and attachments retained.'}
 ],
 adaptations:{tool:'Blender 4.5.9 LTS',approvedParts:selected,
  scripts:[...new Set(selected.map(key=>sourceScripts[key.split(':')[0]]).filter(Boolean))],
  operations:['Local continuous garment or facial silhouette sculpt on the approved parts','Original rest-space rig and texture ownership retained'],
  skeleton:'Existing 65 named bones; original animation clips, weapon sockets and gameplay remain owned by the game',
  retainedBaseline:'assets/characters/rebuilt-v216/sources.json',newExternalModels:[]},files
 },null,2)+'\n');
await fs.writeFile(new URL('hero-refinement-assets.js',root),'// Generated by scripts/pack-hero-refinements.mjs\nexport const HERO_REFINEMENTS='+JSON.stringify({version:217,provenance,files},null,2)+';\n');
// Prior revision sources, hashes and editable GLBs are never rewritten/deleted.
console.log(JSON.stringify(result));
